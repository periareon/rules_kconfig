//! The files of an overrides repository: what overrides_gen.py rendered,
//! byte for byte. A `.config` is overlaid onto a kconfig repository; the
//! `defs.bzl` carries the original defaults and the values that differ, and
//! leaves the transition to `kconfig_override_utils.bzl`.

use std::collections::{BTreeMap, BTreeSet};

use crate::ffi;
use crate::parser::Kconfig;
use crate::repository::starlark_literal;
use crate::settings::{self, Setting};
use crate::{paths, render};

const DEFS_TEMPLATE: &str = r#""""Generated by rules_kconfig. DO NOT EDIT."""

load("@rules_kconfig//kconfig/private:kconfig_override_utils.bzl", "make_kconfig_override_transition", "make_kconfig_overrides_rules")

_ORIGINAL_DEFAULTS = {
{original_defaults}}

_OVERRIDES = {
{overrides}}

_kconfig_overrides_transition = make_kconfig_override_transition(_ORIGINAL_DEFAULTS, _OVERRIDES)

_with_kconfig_overrides, _with_kconfig_overrides_binary, _with_kconfig_overrides_test = make_kconfig_overrides_rules(_kconfig_overrides_transition)

def with_kconfig_overrides(name, actual, executable = False, test = False, **kwargs):
    """Apply .config overrides to a kconfig-dependent target via a transition.

    Args:
        name: Target name.
        actual: The kconfig-dependent target to apply overrides to.
        executable: Set to True when wrapping an executable target (e.g. cc_binary).
        test: Set to True when wrapping a test target (e.g. cc_test).
        **kwargs: Additional attributes forwarded to the underlying rule.
    """
    if test:
        _with_kconfig_overrides_test(name = name, actual = actual, **kwargs)
    elif executable:
        _with_kconfig_overrides_binary(name = name, actual = actual, **kwargs)
    else:
        _with_kconfig_overrides(name = name, actual = actual, **kwargs)
"#;

const BUILD_HEADER: &[u8] = b"# Generated by rules_kconfig. DO NOT EDIT.

load(\"//:defs.bzl\", \"with_kconfig_overrides\")
";

const BUILD_EXPORTS: &[u8] = b"exports_files([\"rendered.config\"])\n";

const BUILD_BODY_TEMPLATE: &str = r#"with_kconfig_overrides(
    name = "config",
    actual = "{kconfig_repo}//:config",
    visibility = ["//visibility:public"],
)

alias(
    name = "lib",
    actual = "{kconfig_repo}//:lib",
    visibility = ["//visibility:public"],
)
"#;

const MENUCONFIG_TEMPLATE: &str = r#"load("@rules_kconfig//kconfig:menuconfig.bzl", "menuconfig")

menuconfig(
    name = "menuconfig",
    config = "{config_ws_path}",
    kconfig = "//:lib",
    visibility = ["//visibility:public"],
)
"#;

/// What the overrides are generated from.
pub struct Request<'a> {
    /// The root Kconfig file, inside the source repository's `kconfig_srcs/`.
    pub kconfig: &'a [u8],
    /// The `kconfig_srcs/` directory.
    pub srctree: &'a [u8],
    /// The `.config` file with the override values.
    pub config: &'a [u8],
    /// The canonical repository prefix of the source kconfig repository.
    pub kconfig_repo: &'a [u8],
    /// The workspace-relative path of `config`, for the `menuconfig` target.
    pub config_ws_path: &'a [u8],
    /// The rendered `.config` of the source repository, if it had defaults.
    pub base_config: Option<&'a [u8]>,
    /// `CONFIG_*` names provided by user rules, skipped in transitions.
    pub settings_labels: &'a [(Vec<u8>, Vec<u8>)],
}

pub struct Outputs {
    pub defs: Vec<u8>,
    pub build: Vec<u8>,
    pub rendered_config: Vec<u8>,
}

/// Sorted dict entries as indented Starlark key-value lines.
fn render_dict_entries(entries: &BTreeMap<Vec<u8>, Vec<u8>>) -> Vec<u8> {
    let mut out = Vec::new();
    for (label, value) in entries {
        out.extend(render::concat(&[b"    \"", label, b"\": ", value, b",\n"]));
    }
    out
}

fn flag_label(kconfig_repo: &[u8], setting: &Setting) -> Vec<u8> {
    render::concat(&[kconfig_repo, b"//:CONFIG_", &setting.name])
}

/// Parse the tree with the `.config` overlaid and render the overrides
/// repository, reading through the session's host.
pub fn generate(request: &Request) -> Result<Outputs, String> {
    let kconfig_path = paths::absolute(request.kconfig);
    let srctree = paths::absolute(request.srctree);
    let config_path = paths::absolute(request.config);
    let parser_srctree = ffi::with(|session| session.srctree.clone());

    let mut kconf = Kconfig::parse(&kconfig_path)?;

    let has_base_config = request.base_config.is_some();
    if let Some(base_config) = request.base_config {
        let base_config_path = paths::absolute(base_config);
        let text = ffi::with(|session| session.host.read(&base_config_path))
            .map_err(|e| e.message(&base_config_path))?;
        kconf.load_config(text, true)?;
    }

    ffi::complete_round()?;

    let filenames = kconf.kconfig_filenames();
    let cache = settings::read_source_files(&filenames, &srctree, |path| {
        ffi::with(|session| session.host.read(path)).ok()
    });
    let labeled: BTreeSet<Vec<u8>> = request
        .settings_labels
        .iter()
        .map(|(name, _)| name.clone())
        .collect();

    let original_settings =
        settings::collect_settings(&kconf, &cache, has_base_config, &labeled, &parser_srctree)?;
    let mut original_defaults = BTreeMap::new();
    for setting in &original_settings {
        if labeled.contains(&setting.config_name()) {
            continue;
        }
        original_defaults.insert(
            flag_label(request.kconfig_repo, setting),
            starlark_literal(&setting.default),
        );
    }

    // Merged, not replaced: a symbol the override file does not mention keeps
    // the base value rather than falling back to its Kconfig default.
    let text = ffi::with(|session| session.host.read(&config_path))
        .map_err(|e| e.message(&config_path))?;
    kconf.load_config(text, false)?;

    let override_settings =
        settings::collect_settings(&kconf, &cache, true, &labeled, &parser_srctree)?;
    let override_by_name: BTreeMap<&[u8], &Setting> = override_settings
        .iter()
        .map(|s| (s.name.as_slice(), s))
        .collect();
    let mut overrides = BTreeMap::new();
    for setting in &original_settings {
        if labeled.contains(&setting.config_name()) {
            continue;
        }
        if let Some(override_setting) = override_by_name.get(setting.name.as_slice())
            && override_setting.default != setting.default
        {
            overrides.insert(
                flag_label(request.kconfig_repo, setting),
                starlark_literal(&override_setting.default),
            );
        }
    }

    let mut build = BUILD_HEADER.to_vec();
    build.push(b'\n');
    build.extend_from_slice(BUILD_EXPORTS);
    build.push(b'\n');
    build.extend(render::template(
        BUILD_BODY_TEMPLATE,
        &[("kconfig_repo", request.kconfig_repo)],
    ));
    build.push(b'\n');
    build.extend(render::template(
        MENUCONFIG_TEMPLATE,
        &[("config_ws_path", request.config_ws_path)],
    ));

    let header = ffi::with(|session| session.getenv(b"KCONFIG_CONFIG_HEADER")).unwrap_or_default();
    let rendered_config = kconf.config_contents(&header)?;

    Ok(Outputs {
        defs: render::template(
            DEFS_TEMPLATE,
            &[
                (
                    "original_defaults",
                    &render_dict_entries(&original_defaults),
                ),
                ("overrides", &render_dict_entries(&overrides)),
            ],
        ),
        build,
        rendered_config,
    })
}
