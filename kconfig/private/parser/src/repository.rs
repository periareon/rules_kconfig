const SETTINGS_BZL_TEMPLATE: &str = r#""""Generated by rules_kconfig. DO NOT EDIT."""

_BOOL_FLAGS = [
{bool_flags}
]

_TRISTATE_FLAGS = [
{tristate_flags}
]

_OTHER_FLAGS = [
{other_flags}
]

_DEFAULTS = {
{defaults}
}

def kconfig_config_settings(*, name, options = {}, visibility = None):
    """Generate config_setting targets for kconfig flags.

    Bool flags produce two config_settings: ``{name}.{CONFIG_*}_Y``
    (matching ``"true"``) and ``{name}.{CONFIG_*}_N`` (matching
    ``"false"``).  Tristate flags produce three config_settings:
    ``{name}.{CONFIG_*}_Y`` (matching ``"y"``),
    ``{name}.{CONFIG_*}_M`` (matching ``"m"``), and
    ``{name}.{CONFIG_*}_N`` (matching ``"n"``).
    Non-bool/non-tristate flags use values from *options*, falling
    back to their Kconfig default when not specified, producing targets
    named ``{name}.{CONFIG_*}_{value}``.  Flags with neither are
    skipped.

    Args:
        name: Prefix for generated target names.
        options: Dict mapping ``CONFIG_*`` names to lists of string
            values.  Each value produces a separate ``config_setting``.
        visibility: Visibility for generated targets.
    """
    for flag in _BOOL_FLAGS:
        native.config_setting(
            name = name + "." + flag.name + "_Y",
            flag_values = {flag: "true"},
            visibility = visibility,
        )
        native.config_setting(
            name = name + "." + flag.name + "_N",
            flag_values = {flag: "false"},
            visibility = visibility,
        )

    for flag in _TRISTATE_FLAGS:
        native.config_setting(
            name = name + "." + flag.name + "_Y",
            flag_values = {flag: "y"},
            visibility = visibility,
        )
        native.config_setting(
            name = name + "." + flag.name + "_M",
            flag_values = {flag: "m"},
            visibility = visibility,
        )
        native.config_setting(
            name = name + "." + flag.name + "_N",
            flag_values = {flag: "n"},
            visibility = visibility,
        )

    for flag in _OTHER_FLAGS:
        values = options.get(flag.name)
        if values == None:
            default = _DEFAULTS.get(flag.name)
            if default == None:
                continue
            values = [default]
        for value in values:
            native.config_setting(
                name = name + "." + flag.name + "_" + str(value),
                flag_values = {flag: str(value)},
                visibility = visibility,
            )
"#;

const SETTINGS_BUILD_TEMPLATE: &str = r#"# Generated by rules_kconfig. DO NOT EDIT.

load("//:settings.bzl", "kconfig_config_settings")

kconfig_config_settings(
    name = "kconfig",{options}
    visibility = ["//visibility:public"],
)
"#;

/// What the repository is generated from.
pub struct Request<'a> {
    pub kconfig: &'a [u8],
    pub srctree: &'a [u8],
    pub repo_name: &'a [u8],
    pub defaults: Option<&'a [u8]>,
    pub config_ws_path: Option<&'a [u8]>,
    /// `CONFIG_*` names mapped to the labels of user-provided build settings.
    pub settings_labels: &'a [(Vec<u8>, Vec<u8>)],
    /// `CONFIG_*` names mapped to the values to generate `config_setting`s
    /// for, as given.
    pub settings_options: Option<&'a Map<String, Vec<String>>>,
    /// The variables the `env` attribute gives the tree, for the manifest.
    pub env: &'a [(Vec<u8>, Vec<u8>)],
}

/// The files of a generated repository.
pub struct Outputs {
    pub build: Vec<u8>,
    pub manifest: Value,
    pub manifest_json: Vec<u8>,
    pub config_h_in: Vec<u8>,
    pub rendered_config: Vec<u8>,
    pub settings_bzl: Vec<u8>,
    pub settings_build: Vec<u8>,
}

/// A default as a Starlark literal.
pub fn starlark_literal(default: &Default) -> Vec<u8> {
    match default {
        Default::Bool(true) => b"True".to_vec(),
        Default::Bool(false) => b"False".to_vec(),
        Default::Int(n) => n.as_bytes().to_vec(),
        Default::Str(s) => {
            let mut out = b"\"".to_vec();
            out.extend(render::escape_starlark(s));
            out.push(b'"');
            out
        }
    }
}

/// A default for a string_dict value: as `starlark_literal`, unquoted.
fn default_as_string(default: &Default) -> Vec<u8> {
    match default {
        Default::Str(s) => render::escape_starlark(s),
        other => starlark_literal(other),
    }
}

fn lines(items: impl Iterator<Item = Vec<u8>>) -> Vec<u8> {
    items.collect::<Vec<_>>().join(&b"\n"[..])
}

fn render_build_file(
    settings: &[Setting],
    repo_name: &[u8],
    root_file: &[u8],
    labels: &[(Vec<u8>, Vec<u8>)],
    config_ws_path: Option<&[u8]>,
) -> Vec<u8> {
    if settings.is_empty() {
        return b"# No Kconfig symbols found.\n".to_vec();
    }
    let label_of = |setting: &Setting| {
        labels
            .iter()
            .find(|(name, _)| *name == setting.config_name())
            .map(|(_, l)| l)
    };
    let flag_rule = |setting: &Setting| {
        if setting.rule == "tristate_flag" {
            "string_flag"
        } else {
            setting.rule
        }
    };

    let mut out = Vec::new();
    let needed_rules: BTreeSet<&str> = settings
        .iter()
        .filter(|s| label_of(s).is_none())
        .map(flag_rule)
        .collect();
    if !needed_rules.is_empty() {
        let quoted: Vec<String> = needed_rules.iter().map(|r| format!("\"{}\"", r)).collect();
        out.extend(
            format!(
                "load(\"@bazel_skylib//rules:common_settings.bzl\", {})\n",
                quoted.join(", ")
            )
            .into_bytes(),
        );
    }
    if !labels.is_empty() {
        out.extend_from_slice(b"load(\"@rules_kconfig//kconfig/private:kconfig_setting_alias.bzl\", \"kconfig_setting_alias\")\n");
    }
    let mut exported = vec![
        repo_name.to_vec(),
        b"kconfig.manifest.json".to_vec(),
        b"rendered.config".to_vec(),
    ];
    for name in &mut exported {
        name.insert(0, b'"');
        name.push(b'"');
    }
    out.extend_from_slice(b"exports_files(glob([\"kconfig_srcs/**\"]) + [");
    out.extend(exported.join(&b", "[..]));
    out.extend_from_slice(b"])\n");

    for setting in settings {
        match label_of(setting) {
            Some(label) => {
                out.extend_from_slice(b"kconfig_setting_alias(\n    name = \"CONFIG_");
                out.extend_from_slice(&setting.name);
                out.extend_from_slice(b"\",\n    actual = \"");
                out.extend_from_slice(label);
                out.extend_from_slice(b"\",\n    visibility = [\"//visibility:public\"],\n)\n");
            }
            None => {
                out.extend_from_slice(flag_rule(setting).as_bytes());
                out.extend_from_slice(b"(\n    name = \"CONFIG_");
                out.extend_from_slice(&setting.name);
                out.extend_from_slice(b"\",\n    build_setting_default = ");
                out.extend(starlark_literal(&setting.default));
                out.extend_from_slice(b",\n    visibility = [\"//visibility:public\"],\n)\n");
            }
        }
    }

    let settings_str = lines(
        settings
            .iter()
            .map(|s| render::concat(&[b"        \":CONFIG_", &s.name, b"\","])),
    );
    let defaults_str = lines(settings.iter().map(|s| {
        render::concat(&[
            b"        \"CONFIG_",
            &s.name,
            b"\": \"",
            &default_as_string(&s.default),
            b"\",",
        ])
    }));
    let types_str = lines(
        settings
            .iter()
            .filter(|s| s.rule == "tristate_flag")
            .map(|s| render::concat(&[b"        \"CONFIG_", &s.name, b"\": \"tristate\","])),
    );
    let kconfig_types_str = lines(settings.iter().map(|s| {
        render::concat(&[
            b"        \"CONFIG_",
            &s.name,
            b"\": \"",
            s.kconfig_type.as_bytes(),
            b"\",",
        ])
    }));
    out.extend(render::template(
        AUTOCONF_TEMPLATE,
        &[
            ("settings", &settings_str),
            ("defaults", &defaults_str),
            ("types", &types_str),
            ("kconfig_types", &kconfig_types_str),
        ],
    ));
    out.extend(render::template(
        KCONFIG_LIBRARY_TEMPLATE,
        &[("root", root_file)],
    ));
    if let Some(config_ws_path) = config_ws_path {
        out.extend(render::template(
            MENUCONFIG_TEMPLATE,
            &[("config_ws_path", config_ws_path)],
        ));
    }
    out
}

/// `config.h.in`: an `#undef` per symbol, and `CONFIG_<name>_MODULE` for a
/// tristate, which the Kconfig tools define for the value `m`.
fn render_config_h_in(settings: &[Setting]) -> Vec<u8> {
    let mut undefs = Vec::new();
    for setting in settings {
        undefs.push(render::concat(&[b"#undef CONFIG_", &setting.name]));
        if setting.kconfig_type == "tristate" {
            undefs.push(render::concat(&[
                b"#undef CONFIG_",
                &setting.name,
                b"_MODULE",
            ]));
        }
    }
    let mut out = b"/* Generated by rules_kconfig. DO NOT EDIT. */\n\n".to_vec();
    out.extend(undefs.join(&b"\n"[..]));
    out.push(b'\n');
    out
}

fn render_settings_bzl(settings: &[Setting], labels: &[(Vec<u8>, Vec<u8>)]) -> Vec<u8> {
    let flag_settings: Vec<&Setting> = settings
        .iter()
        .filter(|s| !labels.iter().any(|(name, _)| *name == s.config_name()))
        .collect();
    let label_line = |s: &&Setting| render::concat(&[b"    Label(\"//:CONFIG_", &s.name, b"\"),"]);
    let bool_lines = lines(
        flag_settings
            .iter()
            .filter(|s| s.rule == "bool_flag")
            .map(label_line),
    );
    let tristate_lines = lines(
        flag_settings
            .iter()
            .filter(|s| s.rule == "tristate_flag")
            .map(label_line),
    );
    let others: Vec<&&Setting> = flag_settings
        .iter()
        .filter(|s| s.rule != "bool_flag" && s.rule != "tristate_flag")
        .collect();
    let other_lines = lines(others.iter().map(|s| label_line(s)));
    let default_lines = lines(others.iter().map(|s| {
        render::concat(&[
            b"    \"CONFIG_",
            &s.name,
            b"\": \"",
            &default_as_string(&s.default),
            b"\",",
        ])
    }));
    render::template(
        SETTINGS_BZL_TEMPLATE,
        &[
            ("bool_flags", &bool_lines),
            ("tristate_flags", &tristate_lines),
            ("other_flags", &other_lines),
            ("defaults", &default_lines),
        ],
    )
}

/// Pairs as a JSON object.
fn object(pairs: &[(Vec<u8>, Vec<u8>)]) -> Value {
    Value::Object(
        pairs
            .iter()
            .map(|(k, v)| (k.clone(), Value::Str(v.clone())))
            .collect(),
    )
}

/// The manifest: the root and every Kconfig file, relative to `srctree`,
/// and what an overrides repository needs to parse the tree again the same
/// way: the labeled settings and the tree's variables.
fn build_manifest(
    filenames: &[Vec<u8>],
    srctree: &[u8],
    has_defaults: bool,
    settings_labels: &[(Vec<u8>, Vec<u8>)],
    env: &[(Vec<u8>, Vec<u8>)],
) -> Result<Value, String> {
    let mut files = Vec::new();
    for filename in filenames {
        let path = if paths::is_absolute(filename) {
            paths::absolute(filename)
        } else {
            paths::absolute(&paths::join(srctree, filename))
        };
        files.push(paths::relative_to(&path, &paths::absolute(srctree))?);
    }
    let root = files
        .first()
        .ok_or("the parser read no Kconfig file")?
        .clone();
    let unique: BTreeSet<Vec<u8>> = files.into_iter().collect();
    let mut manifest = vec![
        (b"root".to_vec(), Value::Str(root)),
        (
            b"files".to_vec(),
            Value::Array(unique.into_iter().map(Value::Str).collect()),
        ),
    ];
    if has_defaults {
        manifest.push((b"config".to_vec(), Value::str("rendered.config")));
    }
    if !settings_labels.is_empty() {
        manifest.push((b"settings_labels".to_vec(), object(settings_labels)));
    }
    if !env.is_empty() {
        manifest.push((b"env".to_vec(), object(env)));
    }
    Ok(Value::Object(manifest))
}

/// Parse the tree and render the files of the repository, reading through
/// the session's host.
pub fn generate(request: &Request) -> Result<Outputs, String> {
    let kconfig_path = paths::absolute(request.kconfig);
    let srctree = paths::absolute(request.srctree);
    let parser_srctree = ffi::with(|session| session.srctree.clone());

    let mut kconf = Kconfig::parse(&kconfig_path)?;

    let has_defaults = request.defaults.is_some();
    if let Some(defaults) = request.defaults {
        let defaults_path = paths::absolute(defaults);
        let text = ffi::with(|session| session.host.read(&defaults_path))
            .map_err(|e| e.message(&defaults_path))?;
        kconf.load_config(text, true)?;
    }

    let filenames = kconf.kconfig_filenames();
    let cache = settings::read_source_files(&filenames, &srctree, |path| {
        ffi::with(|session| session.host.read(path)).ok()
    });
    let labeled: BTreeSet<Vec<u8>> = request
        .settings_labels
        .iter()
        .map(|(name, _)| name.clone())
        .collect();
    let settings =
        settings::collect_settings(&kconf, &cache, has_defaults, &labeled, &parser_srctree)?;

    let manifest = build_manifest(
        &filenames,
        &srctree,
        has_defaults,
        request.settings_labels,
        request.env,
    )?;
    let root = manifest
        .get("root")
        .and_then(Value::as_str)
        .unwrap_or_default()
        .to_vec();

    let options = match request.settings_options {
        Some(settings_options) if !settings_options.is_empty() => {
            let mut sorted: Vec<(&String, &Vec<String>)> = settings_options.iter().collect();
            sorted.sort_by(|a, b| a.0.cmp(b.0));
            let mut option_lines = Vec::new();
            for (name, values) in sorted {
                let values = Value::Array(values.iter().map(Value::str).collect()).dump_ascii()?;
                option_lines.push(render::concat(&[
                    b"        \"",
                    name.as_bytes(),
                    b"\": ",
                    &values,
                    b",",
                ]));
            }
            render::concat(&[
                b"\n    options = {\n",
                &option_lines.join(&b"\n"[..]),
                b"\n    },",
            ])
        }
        _ => Vec::new(),
    };

    let header = ffi::with(|session| session.getenv(b"KCONFIG_CONFIG_HEADER")).unwrap_or_default();
    let rendered_config = kconf.config_contents(&header)?;

    let mut manifest_json = manifest.dump_indented(2)?;
    manifest_json.push(b'\n');
    Ok(Outputs {
        build: render_build_file(
            &settings,
            request.repo_name,
            &root,
            request.settings_labels,
            request.config_ws_path,
        ),
        manifest,
        manifest_json,
        config_h_in: render_config_h_in(&settings),
        rendered_config,
        settings_bzl: render_settings_bzl(&settings, request.settings_labels),
        settings_build: render::template(SETTINGS_BUILD_TEMPLATE, &[("options", &options)]),
    })
}
