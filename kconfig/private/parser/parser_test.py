def test_a_range_bound_is_calculated_before_it_is_read(tmp_path: Path) -> None:
    """An int with a range and no default takes the bound, as kconfiglib did.

    The kernel's own range check stops at the lower bound when the value is
    below it and never calculates the upper one, which the parser then read
    as a null string; the kernel's lib/Kconfig has `BCH_CONST_M` so."""
    _write_tree(
        tmp_path,
        {
            "Kconfig": (
                "config BOUNDED\n\tint\n\trange 5 15\n"
                "config LOW\n\tint\n\tdefault 3\n"
                "config NAMED_BOUNDS\n\tint\n\trange LOW 9\n"
                'config PROMPTED\n\tint "Prompted"\n\trange 5 15\n'
            ),
        },
    )
    response = Host().run(_repository_request(tmp_path / "Kconfig"))
    files = _decoded_files(response)
    assert (
        'name = "CONFIG_BOUNDED",\n    build_setting_default = 5,'
        in files["BUILD.bazel"]
    )
    assert (
        'name = "CONFIG_NAMED_BOUNDS",\n    build_setting_default = 3,'
        in files["BUILD.bazel"]
    )
    # Without a prompt the symbols above are not written; with one the
    # clamped value is.
    assert "CONFIG_PROMPTED=5\n" in files["rendered.config"]


def test_a_symbol_no_config_can_set_keeps_the_calculated_value(
    tmp_path: Path,
) -> None:
    """A shell-tainted symbol without a prompt, or whose prompt's condition
    does not hold, cannot be set by a defaults file; it is not an error that
    the file leaves it out, and it keeps the value the tools calculate. One
    the file sets takes the value set."""
    _write_tree(
        tmp_path,
        {
            "Kconfig": (
                "config PROBE\n\tbool\n\tdefault $(shell,echo y)\n"
                "config OFF\n\tbool\n"
                'config HIDDEN\n\tint "Hidden"\n\tdepends on OFF\n'
                "\tdefault $(shell,echo 4)\n"
                'config SET\n\tint "Set"\n\tdefault $(shell,echo 8)\n'
            ),
        },
    )
    (tmp_path / ".config").write_text("CONFIG_SET=2\n", encoding="utf-8", newline="\n")
    response = Host().run(
        _repository_request(
            tmp_path / "Kconfig",
            defaults=_host_path(tmp_path / ".config"),
            config_ws_path=".config",
        )
    )
    files = _decoded_files(response)
    build = files["BUILD.bazel"]
    assert 'name = "CONFIG_PROBE",\n    build_setting_default = True,' in build
    assert 'name = "CONFIG_HIDDEN",\n    build_setting_default = 0,' in build
    assert 'name = "CONFIG_SET",\n    build_setting_default = 2,' in build

    (tmp_path / ".config").write_text("", encoding="utf-8", newline="\n")
    response = Host().run(
        _repository_request(
            tmp_path / "Kconfig",
            defaults=_host_path(tmp_path / ".config"),
            config_ws_path=".config",
        )
    )
    assert response["status"] == "error"
    assert "CONFIG_SET uses $(shell,...)" in response["message"]
    assert "CONFIG_PROBE" not in response["message"]
    assert "CONFIG_HIDDEN" not in response["message"]


def test_the_variables_given_are_recorded(tmp_path: Path) -> None:
    """The variables of the `env` attribute, which Starlark merges into the
    request's, are kept in the manifest for an overrides repository."""
    _write_tree(
        tmp_path,
        {"Kconfig": 'config BOARD\n\tstring\n\tdefault "$(MODULE_TEST_BOARD)"\n'},
    )
    request = _repository_request(
        tmp_path / "Kconfig", kconfig_env={"MODULE_TEST_BOARD": "k3"}
    )
    request["env"]["MODULE_TEST_BOARD"] = "k3"
    host = Host()
    response = host.run(request)
    files = _decoded_files(response)
    assert (
        'name = "CONFIG_BOARD",\n    build_setting_default = "k3",'
        in files["BUILD.bazel"]
    )
    assert response["manifest"]["env"] == {"MODULE_TEST_BOARD": "k3"}
    assert (
        '"env": {\n    "MODULE_TEST_BOARD": "k3"\n  }' in files["kconfig.manifest.json"]
    )
    # Given ahead, the variable was never asked for.
    assert all("MODULE_TEST_BOARD" not in need["env"] for need in host.needs)


def test_crlf_line_endings_read_as_text(tmp_path: Path) -> None:
    """A tree with CRLF line endings, as a checkout on Windows may have, parses
    as kconfiglib read it: as text. The kernel's lexer alone keeps the `\r`
    at the end of a variable's value."""
    (tmp_path / "Kconfig").write_text(
        'VERSION := $(shell,echo 7)\nconfig INDIRECT\n\tint "Through a variable"\n'
        "\tdefault $(VERSION)\n",
        encoding="utf-8",
        newline="\r\n",
    )
    assert b"\r\n" in (tmp_path / "Kconfig").read_bytes()
    response = Host().run(_repository_request(tmp_path / "Kconfig"))
    files = _decoded_files(response)
    assert "CONFIG_INDIRECT=7\n" in files["rendered.config"]
    # Tainted and visible, the flag keeps the falsey default; the name
    # itself came through without the `\r`.
    assert (
        'name = "CONFIG_INDIRECT",\n    build_setting_default = 0,'
        in files["BUILD.bazel"]
    )
