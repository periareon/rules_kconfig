def test_malformed_payload_is_an_error() -> None:
    """A payload that is not JSON is an error, not a crash."""
    response = json.loads(run_tool(b"not json"))
    assert response["status"] == "error"


def test_bytes_pass_through(tmp_path: Path) -> None:
    """A byte that is not UTF-8 in a source comes back as it went in."""
    (tmp_path / "Kconfig").write_bytes(
        b'config LATIN\n\tstring "Latin"\n\tdefault "caf\xe9"\n'
    )
    request = _repository_request(tmp_path / "Kconfig")
    Host.seed(request, tmp_path)
    payload = json.dumps(request, ensure_ascii=False).encode("utf-8", "surrogateescape")
    assert b"caf\xe9" in payload
    response = run_tool(payload)
    assert b"caf\xe9" in response
    # kconfiglib itself refuses such a file, so the expectation is spelled out.
    decoded = json.loads(response.decode("utf-8", "surrogateescape"))
    assert decoded["status"] == "ok", decoded
    assert (
        'name = "CONFIG_LATIN",\n    build_setting_default = "caf\udce9",'
        in decoded["files"]["BUILD.bazel"]
    )


class TestWindowsPaths:  # pylint: disable=too-few-public-methods
    """Drive paths, which POSIX rules would not treat as absolute."""

    FILES = {
        "C:/tree/Kconfig": 'mainmenu "Win"\n\nconfig A\n\tbool "A"\n\nsource "sub/Kconfig"\n',
        "C:/tree/sub/Kconfig": 'config B\n\tint "B"\n\tdefault 2\n',
    }

    def _serve(self, request: Dict[str, Any]) -> Dict[str, Any]:
        """Answer requests from `FILES`, as Starlark on Windows would, by host path."""
        for _ in range(10):
            response: Dict[str, Any] = json.loads(
                run_tool(json.dumps(request, ensure_ascii=False).encode("utf-8"))
            )
            if response["status"] != "need":
                return response
            for path in response["files"]:
                key = path.replace("\\", "/")
                assert not key.startswith("/"), path
                content = self.FILES.get(key)
                request["files"][path] = {
                    "exists": content is not None,
                    "is_dir": False,
                    "content": content,
                }
            for name in response["env"]:
                request["env"][name] = None
            assert not response["shell"]
        raise AssertionError("the module did not finish")

    def test_paths_are_returned_in_host_form(self) -> None:
        """Every path asked of Starlark is `C:/...`, never `/C:/...`."""
        request: Dict[str, Any] = {
            "command": "repository",
            "env": {},
            "srctree": "C:/tree",
            "kconfig": "C:/tree/Kconfig",
            "files": {},
            "dirs": {},
            "shell": {},
            "repo_name": "win_kconfig",
            "defaults": None,
            "config_ws_path": None,
            "settings_labels": {},
            "settings_options": {},
        }
        response = self._serve(request)
        assert response["status"] == "ok", response
        assert response["manifest"]["files"] == ["Kconfig", "sub/Kconfig"]
        assert response["manifest"]["root"] == "Kconfig"
        files = _decoded_files(response)
        assert (
            'name = "CONFIG_B",\n    build_setting_default = 2,' in files["BUILD.bazel"]
        )
        assert {path.replace("\\", "/") for path in request["files"]} == set(self.FILES)


def _level_tree() -> Dict[str, str]:
    tree = {"Kconfig": "".join(f'source "level1/{i}/Kconfig"\n' for i in range(3))}
    for i in range(3):
        tree[f"level1/{i}/Kconfig"] = (
            f"config L1_{i}\n\tbool\n" + f'source "level2/{i}/Kconfig"\n'
        )
        tree[f"level2/{i}/Kconfig"] = f"config L2_{i}\n\tbool\n\tdefault y\n"
    return tree


def test_a_seeded_request_finishes_in_one_round(tmp_path: Path) -> None:
    """With the tree read ahead there is nothing left to ask for."""
    tree = _level_tree()
    _write_tree(tmp_path, tree)
    request = _repository_request(tmp_path / "Kconfig")
    Host.seed(request, tmp_path)
    host = Host()
    response = host.run(request)
    assert response["status"] == "ok"
    assert host.rounds == 1
    assert sorted(response["manifest"]["files"]) == sorted(tree)


def test_a_listed_directory_answers_for_a_missing_file(tmp_path: Path) -> None:
    """A `source` of a file that is not in its directory's listing costs no round."""
    _write_tree(tmp_path, {"Kconfig": 'source "optional/Kconfig"\n'})
    (tmp_path / "optional").mkdir()
    request = _repository_request(tmp_path / "Kconfig")
    Host.seed(request, tmp_path)
    host = Host()
    response = host.run(request)
    assert response["status"] == "error"
    assert "optional/Kconfig" in response["message"]
    assert host.rounds == 1


def test_a_variable_is_asked_for_when_met(tmp_path: Path, monkeypatch: Any) -> None:
    """`$(NAME)` names a variable the request did not carry; the next round has it."""
    monkeypatch.setenv("MODULE_TEST_BOARD", "k2")
    monkeypatch.delenv("MODULE_TEST_UNSET", raising=False)
    _write_tree(
        tmp_path,
        {
            "Kconfig": (
                'config BOARD\n\tstring\n\tdefault "$(MODULE_TEST_BOARD)"\n'
                'config FALLBACK\n\tstring\n\tdefault "$(MODULE_TEST_UNSET)none"\n'
            ),
        },
    )
    request = _repository_request(tmp_path / "Kconfig")
    Host.seed(request, tmp_path)
    host = Host()
    response = host.run(request)
    assert response["status"] == "ok"
    assert [sorted(name for name in need["env"]) for need in host.needs] == [
        ["MODULE_TEST_BOARD", "MODULE_TEST_UNSET"]
    ]
    files = _decoded_files(response)
    assert (
        'name = "CONFIG_BOARD",\n    build_setting_default = "k2",'
        in files["BUILD.bazel"]
    )
    assert (
        'name = "CONFIG_FALLBACK",\n    build_setting_default = "none",'
        in files["BUILD.bazel"]
    )
    _assert_golden("env", files)


