def _golden(case: str) -> Dict[str, str]:
    """The expected files of a case, by their name in the repository."""
    root = _TESTDATA / case
    return {
        str(path.relative_to(root).as_posix())[: -len(".golden")]: path.read_text(
            encoding="utf-8"
        )
        for path in sorted(root.rglob("*.golden"))
    }


def _assert_golden(case: str, actual: Dict[str, str]) -> None:
    """Compare the files of a response with the case's goldens, or rewrite them."""
    update = os.environ.get("KCONFIG_PARSER_GOLDENS")
    if update:
        root = Path(update) / case
        if root.exists():
            shutil.rmtree(root)
        for name, content in actual.items():
            path = root / (name + ".golden")
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
        return
    expected = _golden(case)
    assert sorted(actual) == sorted(expected)
    for name in sorted(expected):
        assert actual[name] == expected[name], name


class TestRepository:
    """`command: repository` produces the repository kconfiglib produced."""

    def test_matches_python_backend(self, tmp_path: Path) -> None:
        """A tree with sources, a choice, a shell macro and a tainted variable."""
        _write_tree(tmp_path, TREE)
        host = Host()
        response = host.run(
            _repository_request(
                tmp_path / "Kconfig", settings_options={"CONFIG_COUNT": ["1", "3"]}
            )
        )
        files = _decoded_files(response)
        _assert_golden("options", files)
        assert response["manifest"]["files"] == [
            "Kconfig",
            "drivers/a/Kconfig",
            "drivers/b/Kconfig",
            "extra/Kconfig.extra",
        ]
        assert 'default = "héllo"' in files["BUILD.bazel"]
        # The tainted symbols got the falsey defaults, with the shell run through the host.
        assert (
            'name = "CONFIG_TAINTED",\n    build_setting_default = "",'
            in files["BUILD.bazel"]
        )
        assert (
            'name = "CONFIG_INDIRECT",\n    build_setting_default = 0,'
            in files["BUILD.bazel"]
        )

    def test_labels(self, tmp_path: Path) -> None:
        """Labeled symbols become aliases, in the BUILD file and the manifest."""
        _write_tree(tmp_path, TREE)
        labels = {"CONFIG_TAINTED": "@//:tainted", "CONFIG_COUNT": "@//:count"}
        response = Host().run(
            _repository_request(tmp_path / "Kconfig", settings_labels=labels)
        )
        files = _decoded_files(response)
        _assert_golden("labels", files)
        assert response["manifest"]["settings_labels"] == labels

    def test_rounds(self, tmp_path: Path) -> None:
        """The first round asks for the root file; sources follow as they are found."""
        _write_tree(tmp_path, TREE)
        host = Host()
        host.run(_repository_request(tmp_path / "Kconfig"))
        assert host.first_response is not None
        assert host.first_response["status"] == "need"
        assert host.first_response["files"] == [_host_path(tmp_path / "Kconfig")]
        assert 2 < host.rounds <= 8

    def test_a_round_finds_every_file_at_its_level(self, tmp_path: Path) -> None:
        """Rounds go by the depth of the tree, not the number of files in it."""
        tree = _level_tree()
        _write_tree(tmp_path, tree)
        host = Host()
        response = host.run(_repository_request(tmp_path / "Kconfig"))
        assert response["status"] == "ok"
        assert [sorted({Path(f) for f in need["files"]}) for need in host.needs] == [
            [tmp_path / "Kconfig"],
            [tmp_path / f"level1/{i}/Kconfig" for i in range(3)],
            [tmp_path / f"level2/{i}/Kconfig" for i in range(3)],
        ]
        assert sorted(response["manifest"]["files"]) == sorted(tree)

    def test_missing_source_is_an_error(self, tmp_path: Path) -> None:
        """A `source` of a file that does not exist fails as it does natively."""
        _write_tree(tmp_path, {"Kconfig": 'source "nowhere/Kconfig"\n'})
        response = Host().run(_repository_request(tmp_path / "Kconfig"))
        assert response["status"] == "error"
        assert "nowhere/Kconfig" in response["message"]

    def test_defaults(self, tmp_path: Path) -> None:
        """A `.config` of defaults is read through the host and rendered."""
        _write_tree(tmp_path, TREE)
        (tmp_path / ".config").write_text(
            'CONFIG_FOO=y\nCONFIG_COUNT=42\nCONFIG_TAINTED="set"\nCONFIG_INDIRECT=5\n'
            "CONFIG_DRIVER_A=m\nCONFIG_PICK_B=y\n",
            encoding="utf-8",
        )
        response = Host().run(
            _repository_request(
                tmp_path / "Kconfig",
                defaults=_host_path(tmp_path / ".config"),
                config_ws_path="defaults/.config",
            )
        )
        files = _decoded_files(response)
        _assert_golden("defaults", files)
        assert "CONFIG_COUNT=42" in files["rendered.config"]
        assert 'config = "defaults/.config"' in files["BUILD.bazel"]

    def test_missing_tainted_default_is_an_error(self, tmp_path: Path) -> None:
        """The generator's exit with a message becomes an error response."""
        _write_tree(tmp_path, TREE)
        (tmp_path / ".config").write_text(
            "CONFIG_FOO=y\n", encoding="utf-8", newline="\n"
        )
        response = Host().run(
            _repository_request(
                tmp_path / "Kconfig",
                defaults=_host_path(tmp_path / ".config"),
                config_ws_path=".config",
            )
        )
        assert response["status"] == "error"
        assert "CONFIG_TAINTED uses $(shell,...)" in response["message"]
        assert "CONFIG_INDIRECT uses $(shell,...)" in response["message"]

    def test_missing_root_is_an_error(self, tmp_path: Path) -> None:
        """A root Kconfig that does not exist is reported, not retried."""
        response = Host().run(_repository_request(tmp_path / "Kconfig"))
        assert response["status"] == "error"
        assert "Kconfig" in response["message"]


class TestOverrides:  # pylint: disable=too-few-public-methods
    """`command: overrides` produces the repository kconfiglib produced."""

    def test_matches_python_backend(self, tmp_path: Path) -> None:
        """Overrides stacked on a base config, the tree read through the host."""
        srcs = tmp_path / "kconfig_srcs"
        _write_tree(srcs, TREE)
        # The base is the tree's own repository, as `plain` has it.
        (tmp_path / "rendered.config").write_text(
            _golden("plain")["rendered.config"], encoding="utf-8"
        )
        config = tmp_path / "override.config"
        config.write_text(
            'CONFIG_FOO=y\nCONFIG_COUNT=42\nCONFIG_TAINTED="x"\nCONFIG_INDIRECT=1\n',
            encoding="utf-8",
        )

        response = Host().run(
            _request(
                "overrides",
                srcs / "Kconfig",
                srctree=srcs,
                config=_host_path(config),
                base_config=_host_path(tmp_path / "rendered.config"),
                kconfig_repo="@@ext+",
                config_ws_path="override.config",
                settings_labels={},
            )
        )
        files = _decoded_files(response)
        _assert_golden("overrides", files)
        assert '"@@ext+//:CONFIG_COUNT": 42' in files["defs.bzl"]
        assert response["manifest"] is None


