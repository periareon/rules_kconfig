"""Tests of the parser, run natively as `kconfig_tool`.

A small host answers the tool's requests from the filesystem the way the
Starlark loop does, one process per round, and the files it produces are
compared with the golden files under `testdata/`. Those were generated by
the Python backend, kconfiglib and this repository's generators, before it
was removed, so they fix the repository kconfiglib generated for each tree;
the ones a deliberate change touched since (the values of shell-tainted
symbols a defaults file sets or cannot set) were regenerated from the tool.
To regenerate them after such a change, run the test with
`KCONFIG_PARSER_GOLDENS` naming the absolute path of `testdata` (as a
`--test_env`; the sandbox lets the test write there), and review the diff.

The trees use what the kernel's parser accepts: `source` with a path, no
globs and no `rsource`, which were kconfiglib's own.
"""

import json
import os
import platform
import shutil
import subprocess
import textwrap
from pathlib import Path
from typing import Any, Dict, List, Optional

import pytest
from python.runfiles import Runfiles

# The variables `new_request` in `parser_backend.bzl` looks up ahead of the
# first round: the ones the module reads of its own accord.
_PARSER_ENV = [
    "CONFIG_",
    "KCONFIG_CONFIG_HEADER",
]


def _tool() -> Path:
    """The native build of the module."""
    runfiles = Runfiles.Create()
    assert runfiles is not None
    path = runfiles.Rlocation(os.environ["KCONFIG_TOOL"], source_repo="")
    assert path is not None and Path(path).exists(), path
    return Path(path)


def run_tool(payload: bytes) -> bytes:
    """One round: the tool's response to a request."""
    result = subprocess.run(
        [str(_tool())], input=payload, capture_output=True, check=False
    )
    assert result.returncode == 0, result.stderr.decode("utf-8", "replace")
    return result.stdout


class Host:  # pylint: disable=too-few-public-methods
    """Answers the module's requests from the filesystem, like Starlark."""

    def __init__(self) -> None:
        self.rounds = 0
        self.first_response: Optional[Dict[str, Any]] = None
        # Every `need` response, in order.
        self.needs: List[Dict[str, Any]] = []

    def run(self, request: Dict[str, Any], max_rounds: int = 32) -> Dict[str, Any]:
        """Call the tool until it answers with something other than `need`."""
        for _ in range(max_rounds):
            self.rounds += 1
            response: Dict[str, Any] = json.loads(
                run_tool(
                    json.dumps(request, ensure_ascii=False).encode(
                        "utf-8", "surrogateescape"
                    )
                )
            )
            if self.first_response is None:
                self.first_response = response
            if response["status"] != "need":
                return response
            self.needs.append(response)
            for path in response["files"]:
                request["files"][path] = self._stat(path)
            for command in response["shell"]:
                request["shell"][command] = self._shell(command, request["srctree"])
            for name in response["env"]:
                value = os.environ.get(name)
                request["env"][name] = value if value is not None else None
        raise AssertionError("the module did not finish")

    @staticmethod
    def _stat(path: str) -> Dict[str, Any]:
        target = Path(path)
        if not target.exists():
            return {"exists": False, "is_dir": False, "content": None}
        if target.is_dir():
            return {"exists": True, "is_dir": True, "content": None}
        # The file's bytes, as Bazel hands them over.
        return {
            "exists": True,
            "is_dir": False,
            "content": target.read_bytes().decode("utf-8", "surrogateescape"),
        }

    @staticmethod
    def _listdir(path: str) -> Optional[list[list[Any]]]:
        target = Path(path)
        if not target.is_dir():
            return None
        return [[entry.name, entry.is_dir()] for entry in target.iterdir()]

    @staticmethod
    def _shell(command: str, srctree: str) -> Dict[str, Any]:
        # The shell kconfiglib's `subprocess.Popen(shell=True)` would use.
        if platform.system() == "Windows":
            argv = ["cmd.exe", "/c", command]
        else:
            argv = ["/bin/sh", "-c", command]
        result = subprocess.run(
            argv,
            cwd=srctree,
            env=dict(os.environ, srctree=srctree),
            capture_output=True,
            check=False,
        )
        return {
            "stdout": result.stdout.decode("utf-8", "surrogateescape"),
            "stderr": result.stderr.decode("utf-8", "surrogateescape"),
            "return_code": result.returncode,
        }

    @staticmethod
    def seed(request: Dict[str, Any], srctree: Path) -> None:
        """Fill a request as `new_request` in `parser_backend.bzl` does: every
        directory's listing, every `Kconfig*` file and the module's variables."""
        for name in _PARSER_ENV:
            value = os.environ.get(name)
            request["env"][name] = value if value is not None else None
        for directory, _dirs, files in os.walk(srctree):
            request["dirs"][_host_path(directory)] = Host._listdir(directory)
            for name in files:
                if name.startswith("Kconfig"):
                    path = os.path.join(directory, name)
                    request["files"][_host_path(path)] = Host._stat(path)


def _host_path(path: Any) -> str:
    """A path as Starlark gives one to the tool: absolute, with `/` between
    its names on every host (`str(repository_ctx.path(...))` on Windows is
    `C:/...`), which the tool's own paths follow."""
    return Path(path).absolute().as_posix()


def _request(
    command: str, kconfig: Path, srctree: Optional[Path] = None, **fields: Any
) -> Dict[str, Any]:
    srctree = (srctree or kconfig.parent).absolute()
    request: Dict[str, Any] = {
        "command": command,
        "env": {},
        "srctree": _host_path(srctree),
        "kconfig": _host_path(kconfig),
        "files": {},
        "dirs": {},
        "shell": {},
    }
    request.update(fields)
    return request


def _repository_request(kconfig: Path, **fields: Any) -> Dict[str, Any]:
    request = _request(
        "repository",
        kconfig,
        repo_name="test_kconfig",
        defaults=None,
        config_ws_path=None,
        settings_labels={},
        settings_options={},
    )
    request.update(fields)
    return request


def _decoded_files(response: Dict[str, Any]) -> Dict[str, str]:
    assert response["status"] == "ok", response
    return dict(response["files"])


def _write_tree(root: Path, files: Dict[str, str]) -> None:
    for name, content in files.items():
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(textwrap.dedent(content), encoding="utf-8", newline="\n")


